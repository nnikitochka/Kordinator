package su.nnedition.kord.service

import org.apache.commons.lang.RandomStringUtils
import su.nnedition.kord.dao.PlayerDao
import su.nnedition.kord.domain.Player
import su.nnedition.kord.domain.Transcoding
import su.nnedition.kord.domain.User
import su.nnedition.kord.domain.User.Role
import java.util.ArrayList

/** Provides services for maintaining the set of players. */
open class PlayerService(
    private var playerDao: PlayerDao,
    private var statusService: StatusService,
    private var securityService: SecurityService,
    private var transcodingService: TranscodingService
) {
    open fun init() {
        playerDao.deleteOldPlayers(60)
    }

    open fun updatePlayer(player: Player) {
        playerDao.updatePlayer(player)
    }

    open fun getPlayerById(id: Int?): Player? = id?.let(playerDao::getPlayerById)

    open fun getPlayersForUserAndClientId(username: String?, clientId: String?): List<Player> =
        playerDao.getPlayersForUserAndClientId(username, clientId)

    open fun getAllPlayers(): List<Player> = playerDao.getAllPlayers()

    @Synchronized
    open fun removePlayerById(id: Int) {
        playerDao.deletePlayer(id)
    }

    open fun clonePlayer(playerId: Int): Player {
        val player = getPlayerById(playerId) ?: throw NullPointerException()
        if (player.name != null) player.name = player.name + " (copy)"
        createPlayer(player)
        return player
    }

    open fun createPlayer(player: Player?) {
        playerDao.createPlayer(player)
        val transcodings = transcodingService.allTranscodings
        val defaultActiveTranscodings = ArrayList<Transcoding>(transcodings.size)
        for (transcoding in transcodings) {
            if (transcoding.defaultActive) defaultActiveTranscodings.add(transcoding)
        }
        if (player != null) {
            transcodingService.setTranscodingsForPlayer(player, defaultActiveTranscodings)
        }
    }

    open fun getGuestPlayer(): Player {
        var user: User? = securityService.getUserByName(User.USERNAME_GUEST)
        if (user == null) {
            user = User(User.USERNAME_GUEST, null)
            user.roles = setOf(Role.STREAM)
            securityService.createUser(
                user,
                RandomStringUtils.randomAlphanumeric(30),
                "Autogenerated for ${User.USERNAME_GUEST} user"
            )
        }

        val players = getPlayersForUserAndClientId(User.USERNAME_GUEST, null)
        if (players.isNotEmpty()) return players.first()

        val player = Player().apply { username = User.USERNAME_GUEST }
        createPlayer(player)
        return player
    }

    open fun setStatusService(statusService: StatusService) {
        this.statusService = statusService
    }

    open fun setSecurityService(securityService: SecurityService) {
        this.securityService = securityService
    }

    open fun setPlayerDao(playerDao: PlayerDao) {
        this.playerDao = playerDao
    }

    open fun setTranscodingService(transcodingService: TranscodingService) {
        this.transcodingService = transcodingService
    }
}
