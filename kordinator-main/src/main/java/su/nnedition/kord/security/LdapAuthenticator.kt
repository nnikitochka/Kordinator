package su.nnedition.kord.security

import su.nnedition.kord.domain.User
import su.nnedition.kord.service.SecurityService
import su.nnedition.kord.service.SettingsService

/** Neutral LDAP policy and local-user provisioning, independent of Spring Security. */
class LdapAuthenticator(
    private val securityService: SecurityService,
    private val settingsService: SettingsService,
    private val directory: LdapDirectoryAuthenticator
) {
    fun authenticate(username: String, password: String, saltedToken: Boolean): User? {
        if (!settingsService.isLdapEnabled()) {
            throw LdapAuthenticationException(Failure.DISABLED, "LDAP authentication disabled.")
        }
        if (saltedToken) {
            throw LdapAuthenticationException(
                Failure.HASHED_CREDENTIAL,
                "LDAP authentication cannot be done via hashed passwords."
            )
        }

        var user = securityService.getUserByName(username, false)
        if (user == null && !settingsService.isLdapAutoShadowing()) {
            throw LdapAuthenticationException(Failure.USER_NOT_FOUND, "User does not exist.")
        }
        if (user != null && !user.isLdapAuthenticated) {
            throw LdapAuthenticationException(Failure.USER_DISABLED, "LDAP authentication disabled for user.")
        }

        directory.authenticate(username, password)
        if (user == null) {
            val shadow = User(
                username,
                null,
                true,
                0L,
                0L,
                0L,
                setOf(User.Role.STREAM, User.Role.SETTINGS)
            )
            securityService.createUser(shadow, "", "Autogenerated for new LDAP user")
            user = securityService.getUserByName(username, false)
        }
        return user
    }

    enum class Failure { DISABLED, HASHED_CREDENTIAL, USER_NOT_FOUND, USER_DISABLED }

    class LdapAuthenticationException(val failure: Failure, message: String) : RuntimeException(message)
}
