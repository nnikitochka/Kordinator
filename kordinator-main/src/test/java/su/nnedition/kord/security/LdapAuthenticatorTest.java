package su.nnedition.kord.security;

import su.nnedition.kord.domain.User;
import su.nnedition.kord.service.SecurityService;
import su.nnedition.kord.service.SettingsService;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

class LdapAuthenticatorTest {
    private final SettingsService settings = mock(SettingsService.class);
    private final SecurityService security = mock(SecurityService.class);
    private final LdapDirectoryAuthenticator directory = mock(LdapDirectoryAuthenticator.class);

    @Test void rejectsDisabledLdapBeforeDirectoryAccess() {
        when(settings.isLdapEnabled()).thenReturn(false);
        assertThatThrownBy(() -> authenticator().authenticate("alice", "secret", false))
                .isInstanceOf(LdapAuthenticator.LdapAuthenticationException.class)
                .extracting("failure").isEqualTo(LdapAuthenticator.Failure.DISABLED);
        verifyNoInteractions(directory);
    }

    @Test void rejectsSaltedTokensWithoutDirectoryAccess() {
        when(settings.isLdapEnabled()).thenReturn(true);
        assertThatThrownBy(() -> authenticator().authenticate("alice", "token", true))
                .extracting("failure").isEqualTo(LdapAuthenticator.Failure.HASHED_CREDENTIAL);
        verifyNoInteractions(directory);
    }

    @Test void requiresLocalUserUnlessAutoShadowingIsEnabled() {
        when(settings.isLdapEnabled()).thenReturn(true);
        when(settings.isLdapAutoShadowing()).thenReturn(false);
        when(security.getUserByName("alice", false)).thenReturn(null);
        assertThatThrownBy(() -> authenticator().authenticate("alice", "secret", false))
                .extracting("failure").isEqualTo(LdapAuthenticator.Failure.USER_NOT_FOUND);
        verifyNoInteractions(directory);
    }

    @Test void provisionsShadowUserAfterSuccessfulDirectoryBind() {
        when(settings.isLdapEnabled()).thenReturn(true);
        when(settings.isLdapAutoShadowing()).thenReturn(true);
        when(security.getUserByName("alice", false)).thenReturn(null);
        User shadow = new User("alice", null, true, 0L, 0L, 0L,
                java.util.Set.of(User.Role.STREAM, User.Role.SETTINGS));
        when(security.getUserByName("alice", false)).thenReturn(null, shadow);
        when(directory.authenticate("alice", "secret")).thenReturn(new LdapDirectoryAuthenticator.DirectoryIdentity("alice", "uid=alice"));
        assertThat(authenticator().authenticate("alice", "secret", false)).isSameAs(shadow);
        verify(security).createUser(any(User.class), eq(""), eq("Autogenerated for new LDAP user"));
    }

    private LdapAuthenticator authenticator() { return new LdapAuthenticator(security, settings, directory); }
}
