package su.nnedition.kord.security;

import org.junit.Test;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Fixed compatibility fixtures for credential formats in LegacyPasswordEncoders.
 * The values were generated once with the current encoders; keep them independent of encode().
 * Keep these persisted-format fixtures independent of the removed Spring Security codecs.
 */
public class CredentialCompatibilityBaselineTest {

    private static final String PASSWORD = "baseline-password-2026";
    private static final String WRONG_PASSWORD = "baseline-password-2026-wrong";

    // Static outputs from the current registry implementations, not generated by this test.
    private static final String[][] REGISTRY_FIXTURES = {
            {"bcrypt", "$2a$10$fHWmdo8bDJijmKuB5Gf2..JM56ghPw23p118OhNxrHg/.Ss1w9aR6"},
            {"pbkdf2", "ea1c6079718cad1e5dc37ed050d0a81db58f0eed7fd0cf992640561b2ba2271b703dbd6291c213cc"},
            {"scrypt", "$e0801$0Lxz341Wk1Ly2aR2tWBCir8wTMoAvPfIylhlzA/Bo1eBgAC+BIODBfi8PKYQsTJzj7Sh+jGj+cuRGKK8VH3cug==$JyfO1W2E5AFS+mNHxSxqbUVsMEctJ5j+sG4PABUujsE="},
            {"sha256", "658029c5eef2f1ec7505a90f2bc21ddeada8db3160b6ce0e063f0b654db12d46e55f72d2749c8391"},
            {"noop", PASSWORD},
            {"hex", "626173656c696e652d70617373776f72642d32303236"},
            {"legacynoop", PASSWORD},
            {"legacyhex", "626173656c696e652d70617373776f72642d32303236"}
    };

    // Fixed ciphertext made with AesGcmPasswordEncoder("testpass", "2D9AAC35B41C0DB14C8170BE555DC0C9").
    private static final String AES_PASSWORD = "testpass";
    private static final String AES_SALT = "2D9AAC35B41C0DB14C8170BE555DC0C9";
    private static final String AES_CIPHERTEXT =
            "de5d4f9740df9b01c5879829b965f00d07978deb7420dc7453c07cf7b90954a0ca3d893cf771b8f39d38f3667f8e9aa180fa81de7e90";

    @Test
    public void registryFixturesRemainCompatible() throws Exception {
        for (String[] fixture : REGISTRY_FIXTURES) {
            String name = fixture[0];
            String encoded = fixture[1];
            su.nnedition.kord.security.crypto.PasswordEncoder encoder = LegacyPasswordEncoders.CODECS.get(name);

            assertThat(encoder).as("encoder %s exists", name).isNotNull();
            assertThat(encoder.matches(PASSWORD, encoded)).as("%s accepts its stored value", name).isTrue();
            assertThat(encoder.matches(WRONG_PASSWORD, encoded)).as("%s rejects a wrong password", name).isFalse();
            if (LegacyPasswordEncoders.DECODABLE_ENCODERS.contains(name)) {
                assertThat(((PasswordDecoder) encoder).decode(encoded))
                        .as("%s decodes its stored value", name).isEqualTo(PASSWORD);
            }
        }
    }

    @Test
    public void fixedAesGcmCiphertextRemainsReadableAndRejectsTampering() throws Exception {
        AesGcmPasswordEncoder encoder = new AesGcmPasswordEncoder(AES_PASSWORD, AES_SALT);

        assertThat(encoder.matches(PASSWORD, AES_CIPHERTEXT)).isTrue();
        assertThat(encoder.matches(WRONG_PASSWORD, AES_CIPHERTEXT)).isFalse();
        assertThat(encoder.decode(AES_CIPHERTEXT)).isEqualTo(PASSWORD);

        String tampered = AES_CIPHERTEXT.substring(0, AES_CIPHERTEXT.length() - 1) + "1";
        assertThat(encoder.matches(PASSWORD, tampered)).isFalse();
        assertThatThrownBy(() -> encoder.decode(tampered)).isInstanceOf(Exception.class);
    }

}
