package org.airsonic.player.security;

import org.airsonic.player.domain.User;
import org.airsonic.player.service.SecurityService;
import org.airsonic.player.service.SettingsService;

import java.util.Set;

/** Neutral LDAP policy and local-user provisioning, independent of Spring Security. */
public final class LdapAuthenticator {
    private final SecurityService securityService;
    private final SettingsService settingsService;
    private final LdapDirectoryAuthenticator directory;

    public LdapAuthenticator(SecurityService securityService, SettingsService settingsService,
                             LdapDirectoryAuthenticator directory) {
        this.securityService = securityService;
        this.settingsService = settingsService;
        this.directory = directory;
    }

    public User authenticate(String username, String password, boolean saltedToken) {
        if (!settingsService.isLdapEnabled()) throw new LdapAuthenticationException(Failure.DISABLED, "LDAP authentication disabled.");
        if (saltedToken) throw new LdapAuthenticationException(Failure.HASHED_CREDENTIAL,
                "LDAP authentication cannot be done via hashed passwords.");

        User user = securityService.getUserByName(username, false);
        if (user == null && !settingsService.isLdapAutoShadowing())
            throw new LdapAuthenticationException(Failure.USER_NOT_FOUND, "User does not exist.");
        if (user != null && !user.isLdapAuthenticated())
            throw new LdapAuthenticationException(Failure.USER_DISABLED, "LDAP authentication disabled for user.");

        directory.authenticate(username, password);
        if (user == null) {
            User shadow = new User(username, null, true, 0L, 0L, 0L, Set.of(User.Role.STREAM, User.Role.SETTINGS));
            securityService.createUser(shadow, "", "Autogenerated for new LDAP user");
            user = securityService.getUserByName(username, false);
        }
        return user;
    }

    public enum Failure { DISABLED, HASHED_CREDENTIAL, USER_NOT_FOUND, USER_DISABLED }

    public static final class LdapAuthenticationException extends RuntimeException {
        private final Failure failure;

        public LdapAuthenticationException(Failure failure, String message) {
            super(message);
            this.failure = failure;
        }

        public Failure getFailure() { return failure; }
    }
}
