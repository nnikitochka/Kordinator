package org.airsonic.player.service

import com.google.common.io.MoreFiles
import org.apache.commons.configuration2.Configuration
import org.apache.commons.configuration2.FileBasedConfiguration
import org.apache.commons.configuration2.PropertiesConfiguration
import org.apache.commons.configuration2.PropertiesConfigurationLayout
import org.apache.commons.configuration2.builder.FileBasedConfigurationBuilder
import org.apache.commons.configuration2.builder.fluent.Parameters
import org.apache.commons.configuration2.ex.ConfigurationException
import org.apache.commons.configuration2.sync.ReadWriteSynchronizer
import org.slf4j.LoggerFactory
import java.io.IOException
import java.nio.file.Files

class ConfigurationPropertiesService private constructor() {
    private val builder: FileBasedConfigurationBuilder<FileBasedConfiguration>
    private val config: Configuration

    init {
        val propertyFile = SettingsService.getPropertyFile()
        if (!Files.exists(propertyFile)) {
            try {
                MoreFiles.touch(propertyFile)
            } catch (failure: IOException) {
                throw RuntimeException("Could not create new property file", failure)
            }
        }

        val layout = PropertiesConfigurationLayout().apply {
            headerComment = HEADER_COMMENT
            globalSeparator = "="
        }
        builder = FileBasedConfigurationBuilder<FileBasedConfiguration>(PropertiesConfiguration::class.java)
            .configure(
                Parameters().properties()
                    .setFile(propertyFile.toFile())
                    .setSynchronizer(ReadWriteSynchronizer())
                    .setLayout(layout),
            )
        config = try {
            builder.configuration
        } catch (failure: ConfigurationException) {
            throw RuntimeException("Could not load property file at $propertyFile", failure)
        }
    }

    fun save() {
        try {
            builder.save()
        } catch (failure: ConfigurationException) {
            LOG.error("Unable to write to property file.", failure)
        }
    }

    fun containsKey(key: String): Boolean = config.containsKey(key)

    fun clearProperty(key: String) = config.clearProperty(key)

    fun setProperty(key: String, value: Any?) = config.setProperty(key, value)

    fun getProperty(key: String): Any? = config.getProperty(key)

    val configuration: Configuration
        get() = config

    companion object {
        private val LOG = LoggerFactory.getLogger(ConfigurationPropertiesService::class.java)

        const val HEADER_COMMENT = "Airsonic preferences.  NOTE: This file is automatically generated." +
            " Do not modify while application is running"

        @Volatile
        private var instance: ConfigurationPropertiesService? = null

        @JvmStatic
        fun getInstance(): ConfigurationPropertiesService = instance ?: synchronized(this) {
            instance ?: ConfigurationPropertiesService().also { instance = it }
        }

        @JvmStatic
        fun reset() {
            synchronized(this) {
                instance = ConfigurationPropertiesService()
            }
        }
    }
}
