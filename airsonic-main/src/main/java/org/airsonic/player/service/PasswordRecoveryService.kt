package org.airsonic.player.service

import de.triology.recaptchav2java.ReCaptcha
import jakarta.mail.Message
import jakarta.mail.Session
import jakarta.mail.Transport
import jakarta.mail.internet.InternetAddress
import jakarta.mail.internet.MimeMessage
import org.apache.commons.lang.StringUtils
import org.airsonic.player.domain.User
import org.airsonic.player.domain.UserCredential
import org.airsonic.player.domain.UserCredential.App
import org.slf4j.LoggerFactory
import java.time.Instant
import java.util.Date
import java.util.HashMap
import java.util.Properties
import java.security.SecureRandom

/** Password recovery shared by HTTP clients. */
open class PasswordRecoveryService(
    private val settingsService: SettingsService,
    private val securityService: SecurityService
) {
    private val random = SecureRandom()

    open fun configuration(): MutableMap<String, Any> {
        val map = HashMap<String, Any>()
        if (settingsService.isCaptchaEnabled) {
            map["recaptchaSiteKey"] = settingsService.recaptchaSiteKey
        }
        return map
    }

    open fun recover(usernameOrEmail: String?, recaptchaResponse: String?): MutableMap<String, Any> {
        val map = HashMap<String, Any>()
        val normalizedUser = StringUtils.trimToNull(usernameOrEmail)

        if (normalizedUser != null) {
            map["usernameOrEmail"] = normalizedUser
            val user = getUserByUsernameOrEmail(normalizedUser)
            val captchaOk = !settingsService.isCaptchaEnabled || verifyCaptcha(recaptchaResponse)

            if (!captchaOk) {
                map["error"] = "recover.error.invalidcaptcha"
            } else if (user == null) {
                map["error"] = "recover.error.usernotfound"
            } else if (user.email == null) {
                map["error"] = "recover.error.noemail"
            } else {
                val email = user.email!!
                val password = buildString(PASSWORD_LENGTH) {
                    repeat(PASSWORD_LENGTH) { append(SYMBOLS[random.nextInt(SYMBOLS.length)]) }
                }

                if (emailPassword(password, user.username, email)) {
                    map["sentTo"] = email
                    user.isLdapAuthenticated = false
                    securityService.updateUser(user)
                    val credential = UserCredential(
                        user.username,
                        user.username,
                        password,
                        securityService.getPreferredPasswordEncoder(true),
                        App.AIRSONIC,
                        "Autogenerated recovery credentials"
                    )
                    securityService.createCredential(credential)
                } else {
                    map["error"] = "recover.error.sendfailed"
                }
            }
        }
        return map
    }

    protected open fun verifyCaptcha(response: String?): Boolean =
        response != null && ReCaptcha(settingsService.recaptchaSecretKey).isValid(response)

    private fun getUserByUsernameOrEmail(usernameOrEmail: String?): User? {
        if (usernameOrEmail != null) {
            val user = securityService.getUserByName(usernameOrEmail)
            if (user != null) return user
            return securityService.getUserByEmail(usernameOrEmail)
        }
        return null
    }

    /* E-mail user a new password via the configured SMTP server. */
    protected open fun emailPassword(password: String, username: String, email: String): Boolean {
        var protocol = "smtp"
        val smtpServer = settingsService.smtpServer
        if (smtpServer.isNullOrEmpty()) {
            LOG.warn("Can not send email; no Smtp server configured.")
            return false
        }

        val props = Properties()
        when (settingsService.smtpEncryption) {
            "SSL/TLS" -> {
                protocol = "smtps"
                props["mail.$protocol.ssl.enable"] = "true"
            }
            "STARTTLS" -> props["mail.$protocol.starttls.enable"] = "true"
        }
        props["mail.$protocol.host"] = smtpServer
        props["mail.$protocol.port"] = settingsService.smtpPort
        val smtpUser = settingsService.smtpUser
        if (!smtpUser.isNullOrEmpty()) props["mail.$protocol.auth"] = "true"

        val session = Session.getInstance(props, null)
        try {
            val message: Message = MimeMessage(session)
            message.setFrom(InternetAddress(settingsService.smtpFrom))
            message.setRecipients(Message.RecipientType.TO, InternetAddress.parse(email))
            message.setSubject("Airsonic Password")
            message.setText(
                "Hi there!\n\n" +
                    "You have requested to reset your Airsonic password.  Please find your new login details below.\n\n" +
                    "Username: $username\n" +
                    "Password: $password\n\n" +
                    "--\n" +
                    "Your Airsonic server\n" +
                    "airsonic.github.io/"
            )
            message.setSentDate(Date.from(Instant.now()))

            session.getTransport(protocol).use { transport ->
                if (props["mail.$protocol.auth"] == "true") {
                    transport.connect(smtpServer, smtpUser, settingsService.smtpPassword)
                } else {
                    transport.connect()
                }
                transport.sendMessage(message, message.allRecipients)
            }
            return true
        } catch (x: Exception) {
            LOG.warn("Failed to send email.", x)
            return false
        }
    }

    companion object {
        private const val SYMBOLS = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ1234567890"
        private const val PASSWORD_LENGTH = 32
        private val LOG = LoggerFactory.getLogger(PasswordRecoveryService::class.java)
    }
}
