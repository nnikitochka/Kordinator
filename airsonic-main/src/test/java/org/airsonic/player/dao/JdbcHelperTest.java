package org.airsonic.player.dao;

import org.hsqldb.jdbc.JDBCDataSource;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.nio.file.Path;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.Statement;
import java.time.Instant;
import java.util.*;

import static org.junit.jupiter.api.Assertions.*;

class JdbcHelperTest {

    private JDBCDataSource dataSource;
    private TransactionManager transactionManager;
    private JdbcHelper jdbcHelper;

    enum TestStatus {
        ACTIVE, INACTIVE
    }

    static class TestRecord {
        final int id;
        final String name;
        final String status;
        final Instant created;

        TestRecord(int id, String name, String status, Instant created) {
            this.id = id;
            this.name = name;
            this.status = status;
            this.created = created;
        }
    }

    static class TestDao extends AbstractDao {
        void initialize() throws Exception {
            registerInserts("dao_item", "id", List.of("name"), DaoRecord.class);
        }

        Integer insertRecord(DaoRecord record) {
            return insert("dao_item", record);
        }
    }

    static class DaoRecord {
        final String name;

        DaoRecord(String name) {
            this.name = name;
        }
    }

    @BeforeEach
    void setUp() throws Exception {
        dataSource = new JDBCDataSource();
        dataSource.setUrl("jdbc:hsqldb:mem:jdbchelpertest_" + UUID.randomUUID().toString().replace('-', '_'));
        dataSource.setUser("sa");
        dataSource.setPassword("");

        transactionManager = new TransactionManager(dataSource);
        jdbcHelper = new JdbcHelper(dataSource, transactionManager);

        try (Connection conn = dataSource.getConnection(); Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE test_item (" +
                    "id INTEGER GENERATED BY DEFAULT AS IDENTITY (START WITH 1) PRIMARY KEY, " +
                    "name VARCHAR(100), " +
                    "status VARCHAR(50), " +
                    "path_val VARCHAR(255), " +
                    "created TIMESTAMP" +
                    ")");
        }
    }

    @AfterEach
    void tearDown() throws Exception {
        try (Connection conn = dataSource.getConnection(); Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE test_item IF EXISTS");
        }
    }

    @Test
    void basicCrudAndGeneratedKeys() {
        Instant now = Instant.ofEpochMilli(System.currentTimeMillis());

        // Insert and return generated key
        Integer id = jdbcHelper.insertAndReturnKey(
                "INSERT INTO test_item (name, status, path_val, created) VALUES (?, ?, ?, ?)",
                "id",
                "Item1", TestStatus.ACTIVE, Paths.get("/var/music/test"), now);

        assertNotNull(id);
        assertTrue(id > 0);

        // Query with RowMapper
        List<TestRecord> items = jdbcHelper.query(
                "SELECT id, name, status, created FROM test_item WHERE id = ?",
                (rs, rowNum) -> new TestRecord(
                        rs.getInt("id"),
                        rs.getString("name"),
                        rs.getString("status"),
                        rs.getTimestamp("created").toInstant()
                ),
                id);

        assertEquals(1, items.size());
        assertEquals("Item1", items.get(0).name);
        assertEquals("ACTIVE", items.get(0).status);
        assertEquals(now, items.get(0).created);

        // Update
        int updated = jdbcHelper.update("UPDATE test_item SET name = ? WHERE id = ?", "UpdatedName", id);
        assertEquals(1, updated);

        // Query for single types
        List<String> names = jdbcHelper.queryForList("SELECT name FROM test_item WHERE id = ?", String.class, id);
        assertEquals(List.of("UpdatedName"), names);

        // Delete
        int deleted = jdbcHelper.update("DELETE FROM test_item WHERE id = ?", id);
        assertEquals(1, deleted);

        List<Integer> ids = jdbcHelper.queryForList("SELECT id FROM test_item WHERE id = ?", Integer.class, id);
        assertTrue(ids.isEmpty());
    }

    @Test
    void daoJdbcHelpersAndInsertMetadataAreIsolatedPerInstance() throws Exception {
        JDBCDataSource firstDataSource = createDataSource("dao_first");
        JDBCDataSource secondDataSource = createDataSource("dao_second");
        createDaoTable(firstDataSource);
        createDaoTable(secondDataSource);

        TestDao firstDao = new TestDao();
        firstDao.setDataSource(firstDataSource);
        firstDao.initialize();
        TestDao secondDao = new TestDao();
        secondDao.setDataSource(secondDataSource);
        secondDao.initialize();

        Integer firstId = firstDao.insertRecord(new DaoRecord("first"));
        Integer secondId = secondDao.insertRecord(new DaoRecord("second"));

        assertEquals("first", firstDao.getJdbcHelper().queryForList(
                "select name from dao_item where id=?", String.class, firstId).getFirst());
        assertEquals("second", secondDao.getJdbcHelper().queryForList(
                "select name from dao_item where id=?", String.class, secondId).getFirst());
        assertEquals(1, firstDao.getJdbcHelper().queryForList(
                "select count(*) from dao_item", Integer.class).getFirst());
        assertEquals(1, secondDao.getJdbcHelper().queryForList(
                "select count(*) from dao_item", Integer.class).getFirst());
    }

    private JDBCDataSource createDataSource(String name) {
        JDBCDataSource source = new JDBCDataSource();
        source.setUrl("jdbc:hsqldb:mem:" + name + "_" + UUID.randomUUID().toString().replace('-', '_'));
        source.setUser("sa");
        source.setPassword("");
        return source;
    }

    private void createDaoTable(JDBCDataSource source) throws Exception {
        try (Connection conn = source.getConnection(); Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE dao_item (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(100))");
        }
    }

    @Test
    void namedParametersAndCollectionExpansion() {
        jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "One", "ACTIVE");
        jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "Two", "ACTIVE");
        jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "Three", "INACTIVE");

        // Named query with scalar parameters
        Map<String, Object> scalarArgs = Map.of("status", "ACTIVE");
        List<String> activeNames = jdbcHelper.namedQueryForList(
                "SELECT name FROM test_item WHERE status = :status ORDER BY name",
                String.class,
                scalarArgs);
        assertEquals(List.of("One", "Two"), activeNames);

        // Named query with Collection expansion for 'IN (:names)'
        Map<String, Object> collectionArgs = Map.of("names", List.of("One", "Three"));
        List<String> inNames = jdbcHelper.namedQueryForList(
                "SELECT name FROM test_item WHERE name IN (:names) ORDER BY name",
                String.class,
                collectionArgs);
        assertEquals(List.of("One", "Three"), inNames);

        // Named update with collection
        Map<String, Object> deleteArgs = Map.of("names", List.of("One", "Two"));
        int deleted = jdbcHelper.namedUpdate("DELETE FROM test_item WHERE name IN (:names)", deleteArgs);
        assertEquals(2, deleted);

        List<String> remaining = jdbcHelper.queryForList("SELECT name FROM test_item", String.class);
        assertEquals(List.of("Three"), remaining);
    }

    @Test
    void namedParametersEmptyCollectionExpansion() {
        Map<String, Object> emptyArgs = Map.of("names", Collections.emptyList());
        List<String> results = jdbcHelper.namedQueryForList(
                "SELECT name FROM test_item WHERE name IN (:names)",
                String.class,
                emptyArgs);
        assertTrue(results.isEmpty());
    }

    @Test
    void transactionCommitSavesChanges() {
        transactionManager.executeWithoutResult(status -> {
            jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "TxItem1", "ACTIVE");
            jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "TxItem2", "ACTIVE");
        });

        List<String> names = jdbcHelper.queryForList("SELECT name FROM test_item ORDER BY name", String.class);
        assertEquals(List.of("TxItem1", "TxItem2"), names);
    }

    @Test
    void transactionRollbackOnException() {
        assertThrows(IllegalStateException.class, () ->
                transactionManager.executeWithoutResult(status -> {
                    jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "RollbackItem", "ACTIVE");
                    throw new IllegalStateException("Simulated business error");
                })
        );

        List<String> names = jdbcHelper.queryForList("SELECT name FROM test_item", String.class);
        assertTrue(names.isEmpty(), "Changes should have been rolled back");
    }

    @Test
    void transactionRollbackOnlyFlag() {
        transactionManager.executeWithoutResult(status -> {
            jdbcHelper.update("INSERT INTO test_item (name, status) VALUES (?, ?)", "RollbackOnlyItem", "ACTIVE");
            status.setRollbackOnly();
        });

        List<String> names = jdbcHelper.queryForList("SELECT name FROM test_item", String.class);
        assertTrue(names.isEmpty(), "Transaction marked rollback-only should not commit");
    }

    @Test
    void batchUpdateInsertsAllRows() {
        List<Object[]> batch = List.of(
                new Object[]{"Batch1", "ACTIVE"},
                new Object[]{"Batch2", "ACTIVE"},
                new Object[]{"Batch3", "INACTIVE"}
        );

        int count = jdbcHelper.batchedUpdate("INSERT INTO test_item (name, status) VALUES (?, ?)", batch, 2);
        assertEquals(3, count);

        List<String> names = jdbcHelper.queryForList("SELECT name FROM test_item ORDER BY name", String.class);
        assertEquals(List.of("Batch1", "Batch2", "Batch3"), names);
    }
}
